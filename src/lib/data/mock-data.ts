/**
 * Returns true if a real Supabase project URL and anon key have been configured.
 * Returns false if still using dummy/placeholder values.
 */
export function isSupabaseConfigured(): boolean {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (!url || !key) return false;
  if (!url.startsWith('http://') && !url.startsWith('https://')) return false;
  if (url.includes('your-project') || url.includes('placeholder')) return false;
  if (key.includes('placeholder') || key.includes('your_supabase')) return false;
  return true;
}

